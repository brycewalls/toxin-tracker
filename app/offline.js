/* Offline support for the hosted web app (#52). Loaded only by the hosted build (tools/build.mjs), after
   cloud.js; never by the claude.ai artifact or app/preview.html, so CI's page test never registers a worker.
   - Registers sw.js (generated by tools/build.mjs), which keeps the app shell for offline launches.
   - Updates: a new deploy installs a new worker that waits. At launch a waiting worker is applied at once
     (one reload); one found while the app is open shows an 'Update ready' pill whose Reload swaps it in.
     The page reloads only after a swap it asked for, and only once.
   - Status: a calm banner while offline, and a brief 'Synced' toast when changes made offline reach the
     server (BT.sync from core.js's records listener).
   External file, no inline handlers, ready for a strict Content-Security-Policy. Logs nothing about data. */
(function () {
  const BT = window.BT;
  if (!BT) return;

  const css = `
  .ol-banner { position: fixed; left: 50%; transform: translateX(-50%); bottom: calc(88px + env(safe-area-inset-bottom, 0px)); z-index: 30;
    width: min(448px, calc(100% - 32px)); display: flex; align-items: center; gap: 10px; padding: 10px 14px; border-radius: 14px;
    background: var(--card); color: var(--fg); border: 1px solid var(--line); box-shadow: var(--shadow); font-size: 13px; line-height: 1.35; }
  .ol-banner .ic { color: var(--muted); }
  .ol-pill { position: fixed; left: 50%; transform: translateX(-50%); top: calc(env(safe-area-inset-top, 0px) + 10px); z-index: 110;
    display: flex; align-items: center; gap: 12px; padding: 6px 6px 6px 16px; border-radius: 99px; max-width: calc(100% - 32px);
    background: var(--fg); color: var(--bg); font-size: 14px; white-space: nowrap; box-shadow: 0 8px 24px rgba(0,0,0,.18); }
  .ol-pill button { min-height: 36px; padding: 0 14px; border-radius: 99px; background: var(--accent); color: var(--accent-ink); font-weight: 500; }
  body.ol-off .toast { bottom: calc(160px + env(safe-area-inset-bottom, 0px)); }
  body.ol-off #view { padding-bottom: calc(170px + env(safe-area-inset-bottom, 0px)); }`;
  const style = document.createElement('style');
  style.textContent = css;
  document.head.appendChild(style);

  /* ---------- offline banner and Synced toast ---------- */
  let banner = null, offlinePending = false, cacheTimer = null, serverUnreachable = false;
  const isOffline = () => !navigator.onLine || serverUnreachable;
  function status() {
    const off = isOffline();
    document.body.classList.toggle('ol-off', off);
    if (off && !banner) {
      banner = BT.h(`<div class="ol-banner" role="status">${BT.icon('info', 18)}<span>Offline. Changes save on this phone and sync when you are back online.</span></div>`);
      document.body.appendChild(banner);
    } else if (!off && banner) { banner.remove(); banner = null; }
    // 'Synced' only after changes waited for a connection, not after every online save.
    if (BT.sync.pending && off) offlinePending = true;
    if (offlinePending && !BT.sync.pending && !off) { offlinePending = false; BT.toast('Synced'); }
  }
  window.addEventListener('online', status);
  window.addEventListener('offline', status);
  BT.on('status', (s) => {
    // navigator.onLine can say online with no real connection. If Firestore stays on its cache for a while
    // while it has changes to send, treat it as offline too.
    clearTimeout(cacheTimer);
    if (!s.fromCache) serverUnreachable = false;
    else if (navigator.onLine) cacheTimer = setTimeout(() => { if (BT.sync.fromCache && BT.sync.pending && navigator.onLine) { serverUnreachable = true; status(); } }, 8000);
    status();
  });
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', status); else status();

  /* ---------- service worker and updates ---------- */
  const sw = navigator.serviceWorker; // undefined outside secure contexts and when workers are blocked
  if (!sw) return;
  let reloading = false, pill = null;
  sw.addEventListener('controllerchange', () => {
    if (!reloading) return; // the first install claims the page too; that needs no reload
    reloading = 'done';
    location.reload();
  });
  function apply(reg) {
    if (!reg.waiting || reloading) return;
    reloading = true;
    reg.waiting.postMessage({ type: 'skip-waiting' });
  }
  function offer(reg) {
    if (pill || !reg.waiting || !sw.controller) return;
    pill = BT.h(`<div class="ol-pill" role="status"><span>Update ready</span><button type="button">Reload</button></div>`);
    pill.querySelector('button').addEventListener('click', () => { pill.querySelector('button').disabled = true; apply(reg); });
    document.body.appendChild(pill);
  }
  function watch(reg) {
    reg.addEventListener('updatefound', () => {
      const w = reg.installing;
      if (w) w.addEventListener('statechange', () => { if (w.state === 'installed') offer(reg); });
    });
  }
  window.addEventListener('load', async () => {
    let reg;
    try { reg = await sw.register('sw.js'); } catch (e) { console.warn('service worker not registered:', e && e.name); return; }
    if (!reg) return;
    watch(reg);
    // Next launch: a version that finished installing earlier is applied before the app is in use.
    if (reg.waiting && sw.controller) return apply(reg);
    if (reg.installing) {
      const w = reg.installing;
      w.addEventListener('statechange', () => { if (w.state === 'installed') offer(reg); });
    }
    // Home-screen apps resume rather than relaunch, so check for a new deploy when the app comes back, and
    // swap a waiting version in while the app is hidden if nothing is open that a reload would lose.
    document.addEventListener('visibilitychange', () => {
      if (document.visibilityState === 'visible') reg.update().catch(() => {});
      else if (reg.waiting && sw.controller && !BT.sheetOpen()) apply(reg);
    });
  });
})();
